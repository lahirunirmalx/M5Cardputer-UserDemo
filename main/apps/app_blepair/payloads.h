/**
 * @file payloads.h
 * @brief Publicly-documented BLE proximity advert payloads.
 *
 * These are the manufacturer-specific BLE adverts that phones interpret as
 * "nearby device available to pair". They are well-documented in security
 * research papers and public open-source projects (e.g. ESP32 Marauder,
 * Flipper BLE-Spam, ECTO-1A/AppleJuice) - the point of this app is to
 * demonstrate the protocol and let users see how their own phone reacts.
 * Use responsibly: do not spam strangers' devices.
 *
 * Manufacturer IDs:
 *   0x004C - Apple
 *   0x00E0 - Google
 *   0x0075 - Samsung
 *
 * Apple Continuity Proximity-Pair frame layout (type 0x07):
 *   4C 00  07  19  07  <model>  20 75 AA 30  01 00 00  45  12 12 12  00...
 *   |--|   |   |   |    |
 *   id    type len act  device id
 *
 * Apple Nearby-Action frame layout (type 0x04, for AppleTV / Vision Pro etc.):
 *   4C 00  04 04 2A 00 00 00 0F 05 C1 <action> 60 4C 95 00 00 10 00 00 00
 */
#pragma once
#include <stdint.h>
#include <stddef.h>

typedef enum {
    BLE_VENDOR_APPLE,
    BLE_VENDOR_GOOGLE,
    BLE_VENDOR_SAMSUNG,
} ble_vendor_t;

typedef struct {
    const char*    label;
    ble_vendor_t   vendor;
    const uint8_t* mfg_data;   /* full manufacturer-specific data incl. company ID prefix */
    size_t         mfg_len;
} ble_payload_t;

